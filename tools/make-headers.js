#!/usr/bin/env node
'use strict';
/*
 * Writes site/_headers (Netlify): security headers for the whole site and a strict Content-Security-Policy for the
 * demo and the bridge page, where note keys are made and proofs are built.
 *   script-src: only this site, plus the SHA-256 of each page's one inline module script, plus WebAssembly (proofs)
 *   connect-src: this site, the RPCs, explorers and relayer listed in demo/deployments.json, the pinned circuit files
 * Run after any change to demo/index.html, bridge/index.html or the networks in deployments.json:
 *   node tools/make-headers.js          (writes)      node tools/make-headers.js --check   (fails if out of date)
 * The browser tests serve the pages with these exact headers, so a stale hash shows up as a failing test.
 */
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const R = path.resolve(__dirname, '..');
const rd = (p) => fs.readFileSync(path.join(R, p), 'utf8');

function inlineHashes(html) {
  const out = []; const re = /<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g; let m;
  while ((m = re.exec(html))) out.push("'sha256-" + crypto.createHash('sha256').update(m[1], 'utf8').digest('base64') + "'");
  return out;
}
function origins(cfg) {
  const d = cfg || JSON.parse(rd('demo/deployments.json')); const s = new Set();
  const walk = (x) => { if (Array.isArray(x)) x.forEach(walk); else if (x && typeof x === 'object') Object.values(x).forEach(walk); else if (typeof x === 'string' && /^https:\/\//.test(x)) s.add(x.split('/').slice(0, 3).join('/')); };
  walk(d.networks); walk(d.bridge || {});
  s.add('https://cdn.jsdelivr.net');   // circuit files, pinned to a commit and hash-checked in the page
  return [...s].sort();
}
function csp(html, cfg) {
  return ["default-src 'none'", "script-src 'self' " + inlineHashes(html).join(' ') + " 'wasm-unsafe-eval'", "worker-src 'self' blob:",
    "connect-src 'self' " + origins(cfg).join(' '), "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com", "font-src https://fonts.gstatic.com",
    "img-src 'self' data:", "manifest-src 'self'", "base-uri 'none'", "form-action 'none'", "frame-ancestors 'none'"].join('; ');
}
const common = ['  X-Content-Type-Options: nosniff', '  Referrer-Policy: strict-origin-when-cross-origin', '  Strict-Transport-Security: max-age=31536000'];
const block = (paths, policy) => paths.map((p) => [p, '  X-Frame-Options: DENY', '  Content-Security-Policy: ' + policy].join('\n')).join('\n\n');
const out = ['# Generated by tools/make-headers.js — do not edit by hand.', '', ['/*', ...common].join('\n'), '',
  block(['/demo', '/demo/', '/demo/index.html'], csp(rd('demo/index.html'))), '',
  block(['/bridge', '/bridge/', '/bridge/index.html'], csp(rd('bridge/index.html'))), '',
  ['/demo/vendor/*', '  Content-Type: text/javascript; charset=utf-8', '  Cache-Control: public, max-age=31536000, immutable'].join('\n'), ''].join('\n');

/** For tests: the CSP that _headers sets for a page ('demo' or 'bridge'), given the HTML and the deployments they serve. */
function cspFor(html, cfg) { return csp(html, cfg); }
module.exports = { cspFor };

if (require.main === module) {
  const file = path.join(R, 'site', '_headers');
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (cur !== out) { console.error('site/_headers is out of date: run node tools/make-headers.js'); process.exit(1); }
    console.log('site/_headers is up to date');
  } else { fs.writeFileSync(file, out); console.log('wrote ' + file); }
}
